import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const raw = String(process.env.AERO_API_BASE_URL || '').trim().replace(/\/$/, '');
let apiUrl;
try {
  apiUrl = new URL(raw);
} catch {
  throw new Error('AERO_API_BASE_URL must be a valid absolute URL');
}
if (apiUrl.protocol !== 'https:' || apiUrl.pathname !== '/' || apiUrl.search || apiUrl.hash) {
  throw new Error('AERO_API_BASE_URL must be an HTTPS origin without a path, query, or hash');
}

const outputArg = process.argv.indexOf('--output');
const output = outputArg >= 0 ? process.argv[outputArg + 1] : path.join('geo_', 'config.js');
if (!output) throw new Error('--output requires a path');
const content = `// Generated by Netlify. Do not edit the deployed copy.\nwindow.AERO_CONFIG = Object.freeze({ apiBaseUrl: ${JSON.stringify(apiUrl.origin)} });\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, content, 'utf8');
console.log(`Generated ${output} for ${apiUrl.origin}`);
